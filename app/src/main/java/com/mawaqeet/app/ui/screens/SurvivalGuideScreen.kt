/** «دليل الرحلات البرية والصحراء»: دليل دون اتصال بالإنترنت، بطاقات قابلة للتوسيع */
@Composable
fun SurvivalGuideScreen() {
    val env = LocalEnv.current
    val o = AppTheme.ornament
    var query by remember { mutableStateOf("") }
    var open by remember { mutableStateOf(setOf(0)) }
    val q = query.trim().lowercase()

    val visible = sgSections.withIndex().filter { (_, s) ->
        q.isEmpty() || s.title.lowercase().contains(q) || s.summary.lowercase().contains(q) ||
            s.points.any { it.lowercase().contains(q) } || s.links.any { it.label.lowercase().contains(q) }
    }

    ScreenScaffold(title = "دليل الرحلات البرية والصحراء", onBack = env.back, subtitle = "تخطيط وسلامة وعودة، دون إنترنت") {
        ScreenList {
            item {
                Column(Modifier.fillMaxWidth().padding(horizontal = 14.dp, vertical = 6.dp)) {
                    Field("بحث في الدليل", query, { query = it })
                }
            }
            if (visible.isEmpty()) {
                item {
                    Text("لا توجد أقسام مطابقة لبحثك.", Modifier.fillMaxWidth().padding(24.dp), color = o.muted, style = MaterialTheme.typography.bodyMedium)
                }
            }
            visible.forEach { (idx, s) ->
                val expanded = q.isNotEmpty() || idx in open
                item(key = idx) {
                    GlassCard(
                        title = "${idx + 1}. ${s.title}",
                        subtitle = s.summary,
                        onClick = { open = if (idx in open) open - idx else open + idx },
                        trailing = { Text(if (expanded) "▲" else "▼", color = MaterialTheme.colorScheme.primary) }
                    ) {
                        if (expanded) {
                            s.points.forEach { pt ->
                                Row(Modifier.fillMaxWidth().padding(vertical = 4.dp)) {
                                    Text("•", color = o.gold, fontWeight = FontWeight.Black, style = MaterialTheme.typography.bodyMedium)
                                    Spacer(Modifier.width(8.dp))
                                    Text(pt, Modifier.weight(1f), color = o.ink, style = MaterialTheme.typography.bodyMedium)
                                }
                            }
                            if (s.links.isNotEmpty()) {
                                Spacer(Modifier.height(6.dp))
                                Row(Modifier.fillMaxWidth(), horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                                    s.links.forEach { l ->
                                        GlassOutlinedButton(onClick = { env.navigate(l.route) }, nav = true) { Text(l.label) }
                                    }
                                }
                            }
                        } else {
                            Text("اضغط لعرض التفاصيل", color = o.muted, style = MaterialTheme.typography.bodySmall)
                        }
                    }
                }
            }
            item { Note("معلومات عامة للتوعية، وليست بديلاً عن التدريب أو الرعاية الطبية.") }
        }
